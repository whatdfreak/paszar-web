export type AdminDictionary = (typeof translations)[AdminLang];

interface AdminI18nContextValue {
  lang: AdminLang;
  t: AdminDictionary;
  isSwitching: boolean;
  switchLang: (nextLang: AdminLang) => void;
}

const AdminI18nContext = createContext<AdminI18nContextValue>({
  lang: "id",
  t: translations.id,
  isSwitching: false,
  switchLang: () => {},
});

export function AdminI18nProvider({
  children,
}: {
  children: React.ReactNode;
}) {
  const [lang, setLang] = useState<AdminLang>("id");
  const [isSwitching, setIsSwitching] = useState(false);
  const [pendingText, setPendingText] = useState<string>(
    translations.id.switchingText
  );

  useEffect(() => {
    const raf = window.requestAnimationFrame(() => {
      try {
        const saved = window.localStorage.getItem(STORAGE_KEY);
        if (saved === "id" || saved === "en") {
          setLang(saved);
        }
      } catch {
        // Ignore storage read errors
      }
    });
    return () => window.cancelAnimationFrame(raf);
  }, []);

  const switchLang = (nextLang: AdminLang) => {
    if (nextLang === lang || isSwitching) return;
    setPendingText(translations[nextLang].switchingText);
    setIsSwitching(true);

    window.setTimeout(() => {
      setLang(nextLang);
      try {
        window.localStorage.setItem(STORAGE_KEY, nextLang);
      } catch {
        // Ignore storage write errors
      }
      window.setTimeout(() => {
        setIsSwitching(false);
      }, 140);
    }, 220);
  };

  return (
    <AdminI18nContext.Provider
      value={{
        lang,
        t: translations[lang],
        isSwitching,
        switchLang,
      }}
    >
      {children}

      {isSwitching && (
        <div
          aria-live="polite"
          className="fixed inset-0 z-[300] bg-slate-50/80 backdrop-blur-[2px] flex items-center justify-center animate-soft-enter"
        >
          <div className="bg-white border border-slate-200 rounded-xl shadow-lg px-5 py-3.5 flex items-center gap-3">
            <Loader2 className="w-4 h-4 animate-spin text-[#0B1C30]" />
            <span className="text-xs font-semibold text-slate-800">
              {pendingText}
            </span>
          </div>
        </div>
      )}
    </AdminI18nContext.Provider>
  );
}

export function useAdminI18n(): AdminI18nContextValue {
  return useContext(AdminI18nContext);
}
